alter table public.comunidades add column if not exists calha text;
alter table public.comunidades add column if not exists isolada_estiagem boolean not null default false;

create table if not exists public.bairros_familias (
  id bigint generated by default as identity primary key,
  nome text not null unique,
  qtd_familias integer,
  fonte text,
  atualizado_em timestamptz not null default now()
);
alter table public.bairros_familias enable row level security;
create policy bairros_familias_select on public.bairros_familias for select to authenticated using (true);
create policy bairros_familias_insert on public.bairros_familias for insert to authenticated with check (pode_escrever());
create policy bairros_familias_update on public.bairros_familias for update to authenticated using (pode_escrever()) with check (pode_escrever());
create policy bairros_familias_delete on public.bairros_familias for delete to authenticated using (pode_escrever());
